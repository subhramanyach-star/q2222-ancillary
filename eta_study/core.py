G_CHSH=np.array([0,0,0,0,1,1,1,-1.])
def z_ideal(th,ang):
    a0,a1,b0,b1=ang; C=np.cos(2*th); S=np.sin(2*th)
    A=[np.cos(a0)*C,np.cos(a1)*C]; B=[np.cos(b0)*C,np.cos(b1)*C]
    E=[np.cos(a)*np.cos(b)+np.sin(a)*np.sin(b)*S for a in (a0,a1) for b in (b0,b1)]
    return np.array(A+B+E)
def lossy(z,eta,v=1.0):
    z=v*np.asarray(z,float); a=z[:2]; b=z[2:4]; E=z[4:]
    a2=eta*a+(1-eta); b2=eta*b+(1-eta)
    E2=np.array([eta**2*E[2*x+y]+eta*(1-eta)*(a[x]+b[y])+(1-eta)**2 for x in (0,1) for y in (0,1)])
    return np.concatenate([a2,b2,E2])
def z_honest(par,eta,v=1.0): return lossy(z_ideal(par[0],par[1:5]),eta,v)
def loss_functional(g,eta):
    """g.z_eta(ideal z) = c0 + g_eta.z_ideal  (the loss map is affine): returns (c0, g_eta)."""
    g=np.asarray(g,float); a0,a1,b0,b1=g[:4]; E=g[4:]
    c0=(1-eta)*(a0+a1+b0+b1)+(1-eta)**2*E.sum()
    ga=[eta*g[x]+eta*(1-eta)*(E[2*x]+E[2*x+1]) for x in (0,1)]
    gb=[eta*g[2+y]+eta*(1-eta)*(E[y]+E[2+y]) for y in (0,1)]
    return c0,np.concatenate([ga,gb,eta**2*E])
def hbin(p):
    p=np.clip(p,1e-300,1-1e-16); return float(-p*np.log2(p)-(1-p)*np.log2(1-p))
def Hmin_chsh(S):
    S=min(max(S,2.0),2*np.sqrt(2)); return float(-np.log2(0.5+0.5*np.sqrt(max(2-S*S/4,0.0))))
def Hvn_chsh(S):
    S=min(max(S,2.0),2*np.sqrt(2)); return 1-hbin(0.5+0.5*np.sqrt(min(max(S*S/4-1,0.0),1.0)))
class PG:
    """Parametrised NPA guessing-probability SDP (local guess of A_x), single witness or full statistics.
    Returns an UPPER bound on P_guess (valid relaxation) -> lower bound on H_min."""
    def __init__(s,level='1+AB',x=1,mode='single'):
        N=NPA(level); s.mode=mode; cons=[]; obj=0; zt=0; nm=0
        for a in (1,-1):
            y,G=N.block(); cons.append(G>>0); zt=zt+N.z(y); nm=nm+y[N.k1]; obj=obj+(y[N.k1]+a*y[N.kA[x]])/2
        cons.append(nm==1)
        if mode=='single':
            s.g=cp.Parameter(8); s.om=cp.Parameter(); cons.append(s.g@zt>=s.om)
        else:
            s.p=cp.Parameter(8); s.eq=zt==s.p; cons.append(s.eq)
        s.prob=cp.Problem(cp.Maximize(obj),cons)
    def __call__(s,g=None,om=None,p=None):
        if s.mode=='single': s.g.value=np.asarray(g,float); s.om.value=float(om)
        else: s.p.value=np.asarray(p,float)
        try:
            s.prob.solve(solver='CLARABEL',tol_gap_abs=1e-9,tol_gap_rel=1e-9,tol_feas=1e-9,max_iter=300)
            val=s.prob.value
        except Exception: val=None
        if val is None or not np.isfinite(val): return 1.0
        return min(max(val,0.5),1.0)
    def H(s,**kw): return float(-np.log2(s(**kw)))
class PGm:
    """NPA guessing probability of A_x (local guess) or (A_x,B_y) (global guess) under constraints
    R_ge zt >= w_ge (n_ge rows) and R_eq zt == w_eq (n_eq rows).  Upper bound on P_guess -> lower bound on H_min.
    By SDP duality the value equals the best single witness in the cone generated by the rows
    (min over f = sum lam_i R_ge_i + sum nu_j R_eq_j, lam >= 0)."""
    def __init__(s,n_ge,n_eq,level='1+AB',guess=('A',1)):
        N=NPA(level); cons=[]; obj=0; zt=0; nm=0
        labs=[(a,) for a in (1,-1)] if guess[0]=='A' else [(a,b) for a in (1,-1) for b in (1,-1)]
        for lab in labs:
            y,G=N.block(); cons.append(G>>0); zt=zt+N.z(y); nm=nm+y[N.k1]
            if guess[0]=='A': obj=obj+(y[N.k1]+lab[0]*y[N.kA[guess[1]]])/2
            else:
                x,yy=guess[1],guess[2]; a,b=lab
                obj=obj+(y[N.k1]+a*y[N.kA[x]]+b*y[N.kB[yy]]+a*b*y[N.kE[2*x+yy]])/4
        cons.append(nm==1); s.n_ge=n_ge; s.n_eq=n_eq
        if n_ge: s.Rg=cp.Parameter((n_ge,8)); s.wg=cp.Parameter(n_ge); s.cg=s.Rg@zt>=s.wg; cons.append(s.cg)
        if n_eq: s.Re=cp.Parameter((n_eq,8)); s.we=cp.Parameter(n_eq); s.ce=s.Re@zt==s.we; cons.append(s.ce)
        s.prob=cp.Problem(cp.Maximize(obj),cons)
    def __call__(s,z,Rg=None,Re=None):
        z=np.asarray(z,float)
        if s.n_ge: s.Rg.value=np.asarray(Rg,float); s.wg.value=s.Rg.value@z
        if s.n_eq: s.Re.value=np.asarray(Re,float); s.we.value=s.Re.value@z
        val=None
        try:
            s.prob.solve(solver='CLARABEL',tol_gap_abs=1e-8,tol_gap_rel=1e-8,tol_feas=1e-8,max_iter=200)
            val=s.prob.value
        except Exception: pass
        if val is None or not np.isfinite(val): return 1.0
        return min(max(val,0.0),1.0)
    def H(s,z,**kw): return float(-np.log2(max(s(z,**kw),1e-300)))
    def duals(s):
        return (None if not s.n_ge else np.asarray(s.cg.dual_value).ravel(), None if not s.n_eq else np.asarray(s.ce.dual_value).ravel())
def load_opt(V,suf=''):
    """best (highest H) record per (eta, family) over all optimisation/refinement files."""
    import glob, json
    R={}
    for fn in sorted(glob.glob('out/opt%s_v%s_*.jsonl'%(suf,V))):
        for l in open(fn):
            d=json.loads(l); k=(d['eta'],d['fam'])
            if k not in R or d['H']>R[k]['H']+1e-12: R[k]=d
    return R
