"""Detector-inefficiency model and fast (float) min-entropy evaluators for the eta study.
Coordinates z=(a0,a1,b0,b1,E00,E01,E10,E11) in +-1 observables.
Loss model: each detector clicks with prob eta independently; no-click is assigned the outcome +1 (deterministic,
local binning).  For ideal +-1 observables A,B the binned observables are A^eta = eta A + (1-eta) 1 (same for B), so
  a' = eta a + (1-eta),  E' = eta^2 E + eta(1-eta)(a + b) + (1-eta)^2.
White noise (visibility v on the state, before detection): z_ideal -> v z_ideal.
Honest devices: |psi_th> = cos th|00> + sin th|11>, A_x = cos a_x Z + sin a_x X, B_y = cos b_y Z + sin b_y X."""
